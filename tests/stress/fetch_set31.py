#!/usr/bin/env python3
"""Fetch set31 .kicad_pcb sources listed in manifest_set31.json (raw download).

set31 is Koppar's 8-board autorouter benchmark (2026-11-18), from
https://koppar.ai/benchmarks/ ("Autorouter benchmarks, scored by KiCad";
repo Koppar-AI/autorouter-bench, boards/manifest.json): eight professionally
routed open-hardware boards, 2-4 layers, 125-997 connections, which six
routers (Koppar, Freerouting, tscircuit, KiCad Routing Tools 0.1.9,
TraceMaker, Zap!) route from the same placement under a 1200 s cap, scored by
kicad-cli 10.0.4: completion = 1 - unconnected/connections, DRC as errors
added over the human board.

All eight are here. scalenode_cm4 was already in the corpus and moved here
from set6 on 2026-11-18 with its recorded chain; the file set6 fetched is
byte-identical to the benchmark's pin. rp2040_minimal is admitted although
set5's eit_mux was built on it (30 of its 34 symbol ids recur there, dedupe
0.312): a different layout.

Sources are pinned as the benchmark pins them: the KiCad 10.0.4 demo tag on
GitLab, OLIMEX/Antmicro commits on GitHub, and three Raspberry Pi zip archives
(two via the Internet Archive, whose live URLs now serve a later revision). The
three OLIMEX boards and pico_vga are KiCad 5 files with a legacy .pro and no
.kicad_pro (validate_candidate rejects the format; prep_set2's pcbnew load
normalises them, as for set28's KiCad 5 boards). The benchmark itself routes
under its own rules (boards/rules/<name>.json, which also drops the impedance
net classes); this set carries the upstream project as every other set does.

Downloads each board and its sibling project files -- the .kicad_pro (DRC floor,
#441) and the .kicad_dru (per-layer clearance rules, #498) --
into $STRESS_DIR/sources/github_set31/. After fetching, run `bash prep_set31.sh`
(needs KiCad's bundled python / pcbnew) to produce boards_set31/ (routed
reference) + boards_unrouted_set31/ (stripped).

  python3 fetch_set31.py
  bash prep_set31.sh

Auto-generated by assemble_corpus.py.
"""
import json
import os
import shutil
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
STRESS = Path(os.environ.get("STRESS_DIR", str(Path.home() / "Documents/kicad_stress_test")))
MANIFEST = HERE / "manifest_set31.json"


def fetch_archive(b, dest):
    """Board shipped as a .zip (e.g. attached to a GitHub issue) rather than a
    raw .kicad_pcb URL. Download the archive, extract `archive_member` as the
    board, and take its siblings from the SAME directory inside the archive --
    the .kicad_pro (DRC floor, #441) and .kicad_dru (per-layer clearance, #498)
    travel with it. Returns True on success.
    """
    with tempfile.TemporaryDirectory() as td:
        zp = Path(td) / "src.zip"
        r = subprocess.run(["curl", "-sL", "--fail", b["archive_url"], "-o", str(zp)],
                           capture_output=True)
        if r.returncode != 0 or not zp.exists() or zp.stat().st_size == 0:
            return False
        try:
            with zipfile.ZipFile(zp) as z:
                z.extractall(Path(td) / "x")
        except zipfile.BadZipFile:
            return False
        member = Path(td) / "x" / b["archive_member"]
        if not member.exists():
            return False
        shutil.copy(member, dest)
        for ext in (".kicad_pro", ".kicad_dru"):
            sib = member.with_suffix(ext)
            if sib.exists():
                shutil.copy(sib, dest.with_suffix(ext))
        return True


def main():
    boards = json.loads(MANIFEST.read_text())
    out_dir = STRESS / "sources/github_set31"
    out_dir.mkdir(parents=True, exist_ok=True)
    ok = 0
    for b in boards:
        dest = out_dir / Path(b["file"]).name
        if b.get("archive_url"):
            if fetch_archive(b, dest):
                ok += 1
                print(f"  OK  {b['repo']:42} {dest.stat().st_size // 1024}KB  "
                      f"[{b.get('tier','?')}] (archive)")
            else:
                print(f"  FAIL {b['repo']}  <- {b['archive_url']}")
            continue
        r = subprocess.run(["curl", "-sL", "--fail", b["raw_url"], "-o", str(dest)],
                           capture_output=True)
        if r.returncode != 0 or not dest.exists() or dest.stat().st_size == 0:
            print(f"  FAIL {b['repo']}  <- {b['raw_url']}")
            continue
        # siblings: never drop them. Without the .kicad_pro a board resolves its
        # DRC floor from the STOCK netclass (#441); without the .kicad_dru every
        # routing step and check_drc lose the per-layer/conditioned clearance
        # rules that OUTRANK --clearance (#498). A 404 under --fail can still
        # leave a zero-byte file, which reads as "rules present, none" -- drop it.
        for ext in (".kicad_pro", ".kicad_dru"):
            sib = dest.with_suffix(ext)
            subprocess.run(["curl", "-sL", "--fail",
                            b["raw_url"][: -len(".kicad_pcb")] + ext,
                            "-o", str(sib)], capture_output=True)
            if sib.exists() and sib.stat().st_size == 0:
                sib.unlink()
        ok += 1
        print(f"  OK  {b['repo']:42} {dest.stat().st_size // 1024}KB  [{b.get('tier','?')}]")
    print(f"\n{ok}/{len(boards)} set31 sources -> {out_dir}")
    return 0 if ok == len(boards) else 1


if __name__ == "__main__":
    sys.exit(main())
