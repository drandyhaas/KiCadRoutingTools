#!/usr/bin/env python3
"""Fetch set32 .kicad_pcb sources listed in manifest_set32.json (raw download).

set32 is the 25-board Zap! comparison set as Koppar re-ran it (2026-11-18),
from https://koppar.ai/benchmarks/ ("25 more public boards"; repo
Koppar-AI/autorouter-bench, boards/manifest-zap25.json): the open-hardware
boards Zap! (Mutual Solutions) published its router comparison on
(https://zap.mutual.solutions/compare), 2-8 layers, 52-1843 connections, each
under its own project rules, scored as fully connected / clean (0 open,
0 DRC errors) / no more errors than the human board.

All 25 are here. Eight were already in the corpus and moved here on
2026-11-18 with their recorded chains, keeping their corpus names: cm4_lvds
(from set2monster), cvbs_mipi_bridge and pmod_i3c_sensor (set26),
dual_ipex_csi_interposer (set27), hackrf_pro (set1monster), kintex_pcie and
xerxes_cm4_blade (set14) and bitaxe_ultra (set1). Each is re-pinned to the
benchmark's commit, whose .kicad_pcb and .kicad_pro are byte-identical to
the file the old set fetched (bitaxe_ultra's from skot/bitaxe, the benchmark
pins BastelPichi's fork). Two above dedupe_score's 0.30 bar
are admitted as distinct boards: ecp5_dc_scm (0.412 vs set1monster's
artix_dc_scm, Antmicro's shared DC-SCM sheets around a different FPGA; tier
monster, kept with its benchmark) and rp2040_devboard (0.418 vs set4's
rp2040_dev on net names from Raspberry Pi's design guide, no shared symbol
ids, different outline). hackrf_pro is monster-sized too (581 footprints,
the reason it sat in set1monster). gmsl_serializer_board is named apart from
set2monster's gmsl_serializer, a different Antmicro board. si_test_board
has 22 footprints outside its outline upstream and is kept as published. Two
boards ship a .kicad_dru (seven, stm32h7_hdmi_sodimm).

Downloads each board and its sibling project files -- the .kicad_pro (DRC floor,
#441) and the .kicad_dru (per-layer clearance rules, #498) --
into $STRESS_DIR/sources/github_set32/. After fetching, run `bash prep_set32.sh`
(needs KiCad's bundled python / pcbnew) to produce boards_set32/ (routed
reference) + boards_unrouted_set32/ (stripped).

  python3 fetch_set32.py
  bash prep_set32.sh

Auto-generated by assemble_corpus.py.
"""
import json
import os
import shutil
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
STRESS = Path(os.environ.get("STRESS_DIR", str(Path.home() / "Documents/kicad_stress_test")))
MANIFEST = HERE / "manifest_set32.json"


def fetch_archive(b, dest):
    """Board shipped as a .zip (e.g. attached to a GitHub issue) rather than a
    raw .kicad_pcb URL. Download the archive, extract `archive_member` as the
    board, and take its siblings from the SAME directory inside the archive --
    the .kicad_pro (DRC floor, #441) and .kicad_dru (per-layer clearance, #498)
    travel with it. Returns True on success.
    """
    with tempfile.TemporaryDirectory() as td:
        zp = Path(td) / "src.zip"
        r = subprocess.run(["curl", "-sL", "--fail", b["archive_url"], "-o", str(zp)],
                           capture_output=True)
        if r.returncode != 0 or not zp.exists() or zp.stat().st_size == 0:
            return False
        try:
            with zipfile.ZipFile(zp) as z:
                z.extractall(Path(td) / "x")
        except zipfile.BadZipFile:
            return False
        member = Path(td) / "x" / b["archive_member"]
        if not member.exists():
            return False
        shutil.copy(member, dest)
        for ext in (".kicad_pro", ".kicad_dru"):
            sib = member.with_suffix(ext)
            if sib.exists():
                shutil.copy(sib, dest.with_suffix(ext))
        return True


def main():
    boards = json.loads(MANIFEST.read_text())
    out_dir = STRESS / "sources/github_set32"
    out_dir.mkdir(parents=True, exist_ok=True)
    ok = 0
    for b in boards:
        dest = out_dir / Path(b["file"]).name
        if b.get("archive_url"):
            if fetch_archive(b, dest):
                ok += 1
                print(f"  OK  {b['repo']:42} {dest.stat().st_size // 1024}KB  "
                      f"[{b.get('tier','?')}] (archive)")
            else:
                print(f"  FAIL {b['repo']}  <- {b['archive_url']}")
            continue
        r = subprocess.run(["curl", "-sL", "--fail", b["raw_url"], "-o", str(dest)],
                           capture_output=True)
        if r.returncode != 0 or not dest.exists() or dest.stat().st_size == 0:
            print(f"  FAIL {b['repo']}  <- {b['raw_url']}")
            continue
        # siblings: never drop them. Without the .kicad_pro a board resolves its
        # DRC floor from the STOCK netclass (#441); without the .kicad_dru every
        # routing step and check_drc lose the per-layer/conditioned clearance
        # rules that OUTRANK --clearance (#498). A 404 under --fail can still
        # leave a zero-byte file, which reads as "rules present, none" -- drop it.
        for ext in (".kicad_pro", ".kicad_dru"):
            sib = dest.with_suffix(ext)
            subprocess.run(["curl", "-sL", "--fail",
                            b["raw_url"][: -len(".kicad_pcb")] + ext,
                            "-o", str(sib)], capture_output=True)
            if sib.exists() and sib.stat().st_size == 0:
                sib.unlink()
        ok += 1
        print(f"  OK  {b['repo']:42} {dest.stat().st_size // 1024}KB  [{b.get('tier','?')}]")
    print(f"\n{ok}/{len(boards)} set32 sources -> {out_dir}")
    return 0 if ok == len(boards) else 1


if __name__ == "__main__":
    sys.exit(main())
