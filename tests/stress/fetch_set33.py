#!/usr/bin/env python3
"""Fetch set33 .kicad_pcb sources listed in manifest_set33.json (raw download).

set33 is PCBWorld-Bench (2026-11-18), the real-board test sets of PCBWorld
(LG AI Research, arXiv 2607.05915, github.com/LGAI-Research/PCBWorld), as
listed on https://koppar.ai/benchmarks/: D3-A (99 boards, d3a_*) and D3-B
(10, d3b_*), the test split of PCBWorld's configs/datasets/d3.json at
b3d62f5c, drawn from the PCBench collection (github.com/PCBench/PCBench).
All but one are 2-layer, mostly small hobby boards. A board scores only as a
clean pass: every connection made and zero DRC errors under its rules, one
attempt. Published single-attempt scores (D3-A / D3-B): Koppar 1.000 / 1.000,
DeepPCB 0.929 / 0.800, Freerouting 0.75 / 0.64, KiCadRoutingTools 0.74 / 0.20.

All 109 are here: none is in the corpus (no PCBench source repo matches a
corpus repo, dedupe best 0.21 on generic net names, none shares 3 or more
symbol ids with a corpus board).
Each is PCBench's processed.kicad_pcb (KiCad 4/5 format, no project file)
pinned at PCBench dec3be75, the file PCBWorld's chain starts from. The
benchmark then runs that chain (convert_v9, drc_fix_v9, make_guide) to make a
'guide' board and project whose rules the referee judges by; this set is the
unmodified input. The benchmark contains near-copies of itself, kept so the
set matches it: 0001/0002 (an autosave copy), 0048/0051 and 0049/0050
(Pimoroni variants) score 1.0 against each other.

Downloads each board and its sibling project files -- the .kicad_pro (DRC floor,
#441) and the .kicad_dru (per-layer clearance rules, #498) --
into $STRESS_DIR/sources/github_set33/. After fetching, run `bash prep_set33.sh`
(needs KiCad's bundled python / pcbnew) to produce boards_set33/ (routed
reference) + boards_unrouted_set33/ (stripped).

  python3 fetch_set33.py
  bash prep_set33.sh

Auto-generated by assemble_corpus.py.
"""
import json
import os
import shutil
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
STRESS = Path(os.environ.get("STRESS_DIR", str(Path.home() / "Documents/kicad_stress_test")))
MANIFEST = HERE / "manifest_set33.json"


def fetch_archive(b, dest):
    """Board shipped as a .zip (e.g. attached to a GitHub issue) rather than a
    raw .kicad_pcb URL. Download the archive, extract `archive_member` as the
    board, and take its siblings from the SAME directory inside the archive --
    the .kicad_pro (DRC floor, #441) and .kicad_dru (per-layer clearance, #498)
    travel with it. Returns True on success.
    """
    with tempfile.TemporaryDirectory() as td:
        zp = Path(td) / "src.zip"
        r = subprocess.run(["curl", "-sL", "--fail", b["archive_url"], "-o", str(zp)],
                           capture_output=True)
        if r.returncode != 0 or not zp.exists() or zp.stat().st_size == 0:
            return False
        try:
            with zipfile.ZipFile(zp) as z:
                z.extractall(Path(td) / "x")
        except zipfile.BadZipFile:
            return False
        member = Path(td) / "x" / b["archive_member"]
        if not member.exists():
            return False
        shutil.copy(member, dest)
        for ext in (".kicad_pro", ".kicad_dru"):
            sib = member.with_suffix(ext)
            if sib.exists():
                shutil.copy(sib, dest.with_suffix(ext))
        return True


def main():
    boards = json.loads(MANIFEST.read_text())
    out_dir = STRESS / "sources/github_set33"
    out_dir.mkdir(parents=True, exist_ok=True)
    ok = 0
    for b in boards:
        dest = out_dir / Path(b["file"]).name
        if b.get("archive_url"):
            if fetch_archive(b, dest):
                ok += 1
                print(f"  OK  {b['repo']:42} {dest.stat().st_size // 1024}KB  "
                      f"[{b.get('tier','?')}] (archive)")
            else:
                print(f"  FAIL {b['repo']}  <- {b['archive_url']}")
            continue
        r = subprocess.run(["curl", "-sL", "--fail", b["raw_url"], "-o", str(dest)],
                           capture_output=True)
        if r.returncode != 0 or not dest.exists() or dest.stat().st_size == 0:
            print(f"  FAIL {b['repo']}  <- {b['raw_url']}")
            continue
        # siblings: never drop them. Without the .kicad_pro a board resolves its
        # DRC floor from the STOCK netclass (#441); without the .kicad_dru every
        # routing step and check_drc lose the per-layer/conditioned clearance
        # rules that OUTRANK --clearance (#498). A 404 under --fail can still
        # leave a zero-byte file, which reads as "rules present, none" -- drop it.
        for ext in (".kicad_pro", ".kicad_dru"):
            sib = dest.with_suffix(ext)
            subprocess.run(["curl", "-sL", "--fail",
                            b["raw_url"][: -len(".kicad_pcb")] + ext,
                            "-o", str(sib)], capture_output=True)
            if sib.exists() and sib.stat().st_size == 0:
                sib.unlink()
        ok += 1
        print(f"  OK  {b['repo']:42} {dest.stat().st_size // 1024}KB  [{b.get('tier','?')}]")
    print(f"\n{ok}/{len(boards)} set33 sources -> {out_dir}")
    return 0 if ok == len(boards) else 1


if __name__ == "__main__":
    sys.exit(main())
