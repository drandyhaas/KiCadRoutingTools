#!/usr/bin/env python3
"""A pour-coverage probe reads only the layers a terminal has copper on (#1777).

The pour-launch ladders key each fill region to the component of the
terminals it covers, and offer the region's cells next to the OTHER
components as launch cells. Their probe asked the region's fill model about
the terminal's point alone, so a B.Cu pour under an F.Cu pad credited that
pad with a region it does not touch. On the issue's boards (GND pours on
F.Cu and B.Cu, no stitching vias; U1 an SMD pad on F.Cu, U2 / U3 on B.Cu)
the F.Cu region was keyed to U2/U3's component, its cells next to U1 became
Phase 1's targets, and the "route" was a 0.03 mm stub from U1 into the pour
U1 already sits in: it joined nothing and Phase 1 reported success.

  1. `_terminal_layer_test`: an SMD pad's row is on its own layer only;
  2. `_pour_launch_region_cells` (multipoint, `three`): every cell keyed to
     U1's component is on F.Cu and every cell keyed to U2/U3's is on B.Cu,
     and both components are offered cells (non-vacuity);
  3. `_pour_launch_pair_anchors` (2-pad, `two`): the near side's extra rows
     sit on the far side's layer only -- no target anchor on F.Cu beside U1.

The boards are the #1777 attachments (`tests/fixtures/1777`), generated by
pcbnew and filled.

    python3 tests/test_1777_pour_probe_layer.py
"""
import contextlib
import io
import os
import sys

TESTS_DIR = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(TESTS_DIR)
sys.path.insert(0, os.path.join(ROOT, 'py_router'))
sys.path.insert(0, TESTS_DIR)

from kicad_parser import parse_kicad_pcb                       # noqa: E402
from routing_config import GridRouteConfig, GridCoord          # noqa: E402
from connectivity import (get_multipoint_net_pads,             # noqa: E402
                          get_terminal_component_info, get_net_endpoints)
from single_ended_routing import (_terminal_layer_test,        # noqa: E402
                                  _pour_launch_region_cells,
                                  _pour_launch_pair_anchors)
import run_utils                                               # noqa: E402

FIX = os.path.join(TESTS_DIR, 'fixtures', '1777')
failures = []


def check(label, ok, detail=''):
    print(f"  [{'ok' if ok else 'FAIL'}] {label}{(': ' + detail) if detail else ''}")
    if not ok:
        failures.append(label)


def load(name):
    path = os.path.join(FIX, name + '.kicad_pcb')
    run_utils.evidence(path, f'the #1777 board {name}')
    with contextlib.redirect_stdout(io.StringIO()):
        pcb = parse_kicad_pcb(path)
    gnd = next(nid for nid, n in pcb.nets.items() if n.name == 'GND')
    cfg = GridRouteConfig(layers=['F.Cu', 'B.Cu'])
    return pcb, gnd, cfg


def main():
    pcb, gnd, cfg = load('three')
    with contextlib.redirect_stdout(io.StringIO()):
        pad_info = get_multipoint_net_pads(pcb, gnd, cfg)
        comps, _c, _s, _v = get_terminal_component_info(pcb, gnd, pad_info)
    ref = {i: row[5].component_ref for i, row in enumerate(pad_info)}
    by_ref = {r: i for i, r in ref.items()}
    check('three: three GND terminals U1, U2, U3', sorted(by_ref) == ['U1', 'U2', 'U3'],
          str(sorted(by_ref)))

    # 1. the row test
    on = _terminal_layer_test(pcb, gnd, cfg.layers)
    u1 = pad_info[by_ref['U1']]
    u2 = pad_info[by_ref['U2']]
    check('U1 (SMD, F.Cu) is on F.Cu', on(u1, 'F.Cu'))
    check('U1 is NOT on B.Cu', not on(u1, 'B.Cu'))
    check('U2 (SMD, B.Cu) is on B.Cu and not on F.Cu',
          on(u2, 'B.Cu') and not on(u2, 'F.Cu'))

    # 2. the multipoint ladder
    c1 = comps.get(by_ref['U1'], by_ref['U1'])
    c2 = comps.get(by_ref['U2'], by_ref['U2'])
    check('U2 and U3 share the B.Cu pour component, U1 is apart',
          comps.get(by_ref['U3'], by_ref['U3']) == c2 and c1 != c2)
    coord = GridCoord(cfg.grid_step)
    with contextlib.redirect_stdout(io.StringIO()):
        cells = _pour_launch_region_cells(pcb, gnd, pad_info, comps, cfg.layers,
                                          coord, {}, cfg)
    l1 = sorted({k[2] for k in (cells.get(c1) or {})})
    l2 = sorted({k[2] for k in (cells.get(c2) or {})})
    check("U1's component is offered launch cells (non-vacuity)", bool(l1))
    check("U2/U3's component is offered launch cells (non-vacuity)", bool(l2))
    check("U1's cells are all on F.Cu, the layer of the pour U1 is in",
          l1 == [0], f'layers {l1}')
    check("U2/U3's cells are all on B.Cu: none on F.Cu beside U1 (the false success)",
          l2 == [1], f'layers {l2}')

    # 3. the 2-pad anchors
    pcb, gnd, cfg = load('two')
    with contextlib.redirect_stdout(io.StringIO()):
        src, tgt, err = get_net_endpoints(pcb, gnd, cfg)
        ex_s, ex_t = _pour_launch_pair_anchors(pcb, gnd, src, tgt, cfg.layers,
                                               GridCoord(cfg.grid_step), cfg)
    check('two: endpoints derived', not err and src and tgt, str(err))
    # which side holds U1 (F.Cu, layer 0)?
    u1_src = any(r[2] == 0 for r in src)
    near_u1 = ex_t if u1_src else ex_s     # anchors offered to reach U1's side
    near_u2 = ex_s if u1_src else ex_t
    check('anchors are offered on both sides (non-vacuity)',
          bool(near_u1) and bool(near_u2), f'{len(ex_s)} source, {len(ex_t)} target')
    check("U2's pour anchors (offered beside U1) are all on B.Cu",
          {r[2] for r in near_u1} == {1}, str(sorted({r[2] for r in near_u1})))
    check("U1's pour anchors (offered beside U2) are all on F.Cu",
          {r[2] for r in near_u2} == {0}, str(sorted({r[2] for r in near_u2})))

    if failures:
        print(f'FAILED: {len(failures)} check(s): {failures}')
        return 1
    print('PASS')
    return 0


if __name__ == '__main__':
    sys.exit(main())
