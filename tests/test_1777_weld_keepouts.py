#!/usr/bin/env python3
"""Pour-launch welds and seeded terminals keep out of keep-out areas (#1777).

A rule area forbidding tracks (no net filter, pour allowed) over a GND pad:
the A* honours it, but the terminal copper laid outside the search did not.

  - a pour-launch cell (multipoint ladder, 2-pad pair anchors) became an
    endpoint override inside the area, and its bridge to the fill weld point
    shipped there (`three`, `two`);
  - a #479 seeded on-pad cell welded back to the pad centre, which the area
    covered (`bridge-ko`, a 0.6 mm track);
  - the bridge drop for a keep-out (#1442) covered one through via only.

Now (all in the shared engine):

  1. `_launch_weld_test` refuses a launch cell whose terminal copper (grid
     point and bridge) reaches into an area forbidding tracks on its layer,
     and passes the same weld on a layer or at a spot no area covers;
  2. a seeded cell is offered only where a track end clears the area
     (`_keepout_clear_cells`), and welds to its own grid point;
  3. a terminal bridge reaching into the area is DROPPED when its grid end
     already sits on the terminal's own copper
     (`_bridge_adds_nothing_in_keepout`), and kept otherwise;
  4. every converted route's copper is gated (`_route_keepout_refusal`):
     the 0.1 mm grid step main laid between two override cells on `two` is
     refused, and the same step on the other layer is not;
  5. end to end, route.py on the issue's six boards ships no copper inside
     a forbidding area (`rule_area_audit`) and leaves GND connected
     (`check_connected`): the three that violated at main (three, two,
     bridge-ko) and the three controls (nok-three: the area away from the
     pads; via-ko-v: vias allowed; bridge-ko-two: two pads).

The boards are the #1777 attachments (`tests/fixtures/1777`), generated by
pcbnew and filled. Part 0 runs checks 1-4.

    python3 tests/test_1777_weld_keepouts.py [--part I/3]
"""
import argparse
import contextlib
import io
import os
import shutil
import subprocess
import sys
import tempfile

TESTS_DIR = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(TESTS_DIR)
sys.path.insert(0, os.path.join(ROOT, 'py_router'))
sys.path.insert(0, TESTS_DIR)

from kicad_parser import parse_kicad_pcb, Segment               # noqa: E402
from routing_config import GridRouteConfig, GridCoord           # noqa: E402
from check_drc import rule_area_audit                           # noqa: E402
from single_ended_routing import (_launch_weld_test,            # noqa: E402
                                  _keepout_gate, _keepout_clear_cells,
                                  _bridge_adds_nothing_in_keepout,
                                  _route_keepout_refusal)
import run_utils                                                # noqa: E402

RUN_ALL_PARTS = 3

FIX = os.path.join(TESTS_DIR, 'fixtures', '1777')
CASES = ['three', 'two', 'bridge-ko', 'nok-three', 'via-ko-v', 'bridge-ko-two']
failures = []


def check(label, ok, detail=''):
    print(f"  [{'ok' if ok else 'FAIL'}] {label}{(': ' + detail) if detail else ''}")
    if not ok:
        failures.append(label)


def load(name):
    path = os.path.join(FIX, name + '.kicad_pcb')
    run_utils.evidence(path, f'the #1777 board {name}')
    with contextlib.redirect_stdout(io.StringIO()):
        pcb = parse_kicad_pcb(path)
    gnd = next(nid for nid, n in pcb.nets.items() if n.name == 'GND')
    return pcb, gnd, GridRouteConfig(layers=['F.Cu', 'B.Cu'])


def units():
    # 1. launch cells (three: area F.Cu (18,8)-(22,12) around U1 at (20,10))
    pcb, gnd, cfg = load('three')
    coord = GridCoord(cfg.grid_step)
    ok = _launch_weld_test(pcb, gnd, cfg, coord, cfg.layers, frozenset())
    check('launch weld beside U1 on F.Cu, inside the area, is refused',
          not ok(20.02, 10.02, 0))
    check('the same weld on B.Cu (no area there) is offered', ok(20.02, 10.02, 1))
    check('a weld on F.Cu away from the area is offered', ok(30.02, 15.02, 0))
    check('a weld just outside, whose bridge disc reaches in, is refused',
          not ok(22.05, 10.02, 0))

    # 2. seeded cells (bridge-ko: area F.Cu (19.5,9.7)-(20.1,11.6), U1 pad
    #    1.5 mm at (20,10))
    pcb, gnd, cfg = load('bridge-ko')
    coord = GridCoord(cfg.grid_step)
    gate = _keepout_gate(pcb)
    check('bridge-ko has a forbidding area', gate is not None)
    kept = _keepout_clear_cells([(200, 100), (206, 100)], gate, gnd, cfg,
                                'F.Cu', coord)
    check('a seeded cell at the pad centre (inside the area) is dropped, one '
          'at x=20.6 kept', kept == [(206, 100)], str(kept))
    check('B.Cu (no area) keeps both',
          _keepout_clear_cells([(200, 100), (206, 100)], gate, gnd, cfg,
                               'B.Cu', coord) == [(200, 100), (206, 100)])

    # 3. bridge drop
    check("main's 0.6 mm bridge (20.6,10)->(20,10): refused and on U1's own "
          "copper -> dropped",
          _bridge_adds_nothing_in_keepout(pcb, gnd, cfg, 'F.Cu', (20.6, 10.0),
                                          (20.0, 10.0)))
    check('a bridge from off the pad (21.0,10) is NOT dropped (it joins the pad; '
          'the backstop fails it instead)',
          not _bridge_adds_nothing_in_keepout(pcb, gnd, cfg, 'F.Cu', (21.0, 10.0),
                                              (20.0, 10.0)))
    pcb_n, gnd_n, _ = load('nok-three')
    check('a bridge no area reaches is never dropped (nok-three)',
          not _bridge_adds_nothing_in_keepout(pcb_n, gnd_n, cfg, 'F.Cu',
                                              (20.1, 10.0), (20.0, 10.0)))

    # 4. the route backstop (two: area F.Cu (18,8)-(22,12))
    pcb, gnd, cfg = load('two')
    step = dict(start_x=20.0, start_y=10.0, end_x=20.1, end_y=10.0, width=0.3,
                net_id=gnd)
    why = _route_keepout_refusal(pcb, [Segment(layer='F.Cu', **step)], [])
    check("main's 0.1 mm grid step on F.Cu inside the area is refused",
          bool(why) and 'keep-out' in why[0], str(why))
    check('the same step on B.Cu is not',
          _route_keepout_refusal(pcb, [Segment(layer='B.Cu', **step)], []) is None)


def route_case(tmp, name):
    src = os.path.join(FIX, name + '.kicad_pcb')
    run_utils.evidence(src, f'the #1777 board {name}')
    inp = os.path.join(tmp, name + '.kicad_pcb')
    out = os.path.join(tmp, name + '.routed.kicad_pcb')
    shutil.copyfile(src, inp)
    env = dict(os.environ, PYTHONUTF8='1')
    r = subprocess.run([sys.executable, '-X', 'utf8', 'py_router/route.py', inp, out,
                        '--nets', '*', '--layers', 'F.Cu', 'B.Cu',
                        '--escalation', 'off', '--no-fix-drc-settings'],
                       cwd=ROOT, env=env, capture_output=True, text=True,
                       encoding='utf-8', errors='replace')
    if r.returncode != 0 or not os.path.isfile(out):
        check(f'{name}: route.py ran', False,
              f'exit {r.returncode}: {(r.stdout + r.stderr)[-600:]}')
        return
    run_utils.evidence(out, f'the routed {name}')
    with contextlib.redirect_stdout(io.StringIO()):
        pcb = parse_kicad_pcb(out)
    found = rule_area_audit(pcb, pcb.segments, pcb.vias)
    check(f'{name}: the board has a forbidding area', found is not None)
    check(f'{name}: no routed copper inside a forbidding area', found == [],
          str(found))
    c = subprocess.run([sys.executable, '-X', 'utf8', 'py_router/check_connected.py',
                        out, '--quiet'], cwd=ROOT, env=env, capture_output=True,
                       text=True, encoding='utf-8', errors='replace')
    check(f'{name}: GND connected (check_connected)',
          c.returncode == 0 and 'OK' in c.stdout,
          '' if c.returncode == 0 else f'exit {c.returncode}: {c.stdout[-300:]}')


def _part(text):
    i, _, n = text.partition('/')
    i, n = int(i), int(n)
    if not 0 <= i < n:
        raise argparse.ArgumentTypeError(f'--part {text}: need 0 <= I < N')
    return i, n


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--part', type=_part, default=None, metavar='I/N')
    a = ap.parse_args()
    i, n = a.part or (0, 1)
    if i == 0:
        units()
    cases = CASES[i::n]
    tmp = tempfile.mkdtemp(prefix='t1777_')
    try:
        for name in cases:
            route_case(tmp, name)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    if failures:
        print(f'FAILED: {len(failures)} check(s): {failures}')
        return 1
    print('PASS')
    return 0


if __name__ == '__main__':
    sys.exit(main())
